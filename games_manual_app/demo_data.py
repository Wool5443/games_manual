def seed_demo_games(db: sqlite3.Connection) -> int:
    """Add missing demo games atomically, preserving existing matching records."""
    inserted = 0
    with db:
        for game in DEMO_GAMES:
            cursor = db.execute(
                """
                INSERT INTO games (
                    title, game_type, goal, participants, age_category, duration,
                    location, equipment, rules, files_json, created_by_email,
                    created_by_name, created_at, updated_at
                )
                SELECT :title, :game_type, :goal, :participants, :age_category,
                       :duration, :location, :equipment, :rules, '[]',
                       :author_email, :author_name, :created_at, :created_at
                WHERE NOT EXISTS (
                    SELECT 1 FROM games
                    WHERE title = :title AND created_by_email = :author_email
                )
                """,
                {**game, "author_email": DEMO_AUTHOR_EMAIL, "author_name": DEMO_AUTHOR_NAME},
            )
            inserted += cursor.rowcount
    return inserted
